"""Builds NoteHawk's icon fonts from Microsoft's Fluent UI System Icons (MIT) and writes the matching C# constants.

Each icon gets a private-use code point; the app refers to icons by name through the Ic class (Models/Ic.cs),
e.g. Text="{x:Static m:Ic.Home}" in XAML or Ic.Home in code.

    python tools/make_icon_font.py <path to fluentui-system-icons/fonts>

Output: src/NoteHawk.Desktop/Assets/Fonts/NoteHawkIcons-{Regular,Filled}.ttf and src/NoteHawk.Desktop/Models/Ic.cs
"""
import json, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._c_m_a_p import cmap_format_4

# C# name -> Fluent icon name. Code points are assigned in this order from U+E000, so only ever append.
ICONS = [
    ('Home', 'home'), ('Note', 'note'), ('Notebook', 'notebook'), ('BookOpen', 'book_open'),
    ('Task', 'task_list_ltr'), ('Tag', 'tag'), ('Shared', 'people_team'), ('Share', 'share'),
    ('Template', 'document_one_page'), ('Delete', 'delete'), ('Settings', 'settings'), ('Sun', 'weather_sunny'),
    ('Moon', 'weather_moon'), ('Add', 'add'), ('Search', 'search'), ('ChevronDown', 'chevron_down'),
    ('ChevronRight', 'chevron_right'), ('ChevronLeft', 'chevron_left'), ('More', 'more_horizontal'), ('Star', 'star'),
    ('Bold', 'text_bold'), ('Italic', 'text_italic'), ('Underline', 'text_underline'),
    ('Strike', 'text_strikethrough'), ('TextColor', 'text_color'), ('Highlight', 'highlight'),
    ('Bullets', 'text_bullet_list_ltr'), ('Numbers', 'text_number_list_ltr'), ('Checked', 'checkbox_checked'),
    ('Unchecked', 'checkbox_unchecked'), ('Table', 'table'), ('Image', 'image'), ('Attach', 'attach'),
    ('Link', 'link'), ('Pen', 'pen'), ('Ink', 'ink_stroke'), ('Mic', 'mic'), ('Undo', 'arrow_undo'),
    ('Redo', 'arrow_redo'), ('Cloud', 'cloud'), ('CloudDone', 'cloud_checkmark'), ('Lock', 'lock_closed'),
    ('Filter', 'filter'), ('Sort', 'arrow_sort'), ('Clock', 'clock'), ('Globe', 'globe'), ('Pin', 'pin'),
    ('Calendar', 'calendar_ltr'), ('Alert', 'alert'), ('Indent', 'text_indent_increase_ltr'),
    ('Check', 'checkmark'), ('Dismiss', 'dismiss'), ('Folder', 'folder'), ('Download', 'arrow_download'),
    ('Sparkle', 'sparkle'), ('Pdf', 'document_pdf'), ('ScanText', 'scan_text'), ('Section', 'notebook_section'),
    ('People', 'people'), ('Document', 'document_text'), ('Sync', 'arrow_sync'), ('Font', 'text_font'),
    ('FontSize', 'text_font_size'), ('Brush', 'paint_brush'), ('Info', 'info'), ('Idea', 'lightbulb'),
    ('Compose', 'compose'), ('Header', 'text_header_1'), ('Code', 'code'), ('Shape', 'draw_shape'),
    ('NoteAdd', 'note_add'), ('BookAdd', 'book_add'), ('Import', 'arrow_import'), ('Eye', 'eye'),
    ('History', 'history'), ('Help', 'question_circle'), ('Person', 'person'), ('Mail', 'mail'),
    ('Board', 'board'), ('Grid', 'grid_dots'), ('Circle', 'circle'),
]
CP = {name: 0xE000 + i for i, (name, _) in enumerate(ICONS)}


def build(src_dir, style, family, out_dir):
    names = json.load(open(f'{src_dir}/FluentSystemIcons-{style}.json'))
    font = TTFont(f'{src_dir}/FluentSystemIcons-{style}.ttf')
    cmap = font.getBestCmap()
    chosen = {}
    for name, fluent in ICONS:
        for size in (20, 24, 16, 28):
            key = f'ic_fluent_{fluent}_{size}_{style.lower()}'
            if key in names:
                chosen[CP[name]] = cmap[names[key]]
                break
        else:
            sys.exit(f'missing icon: {fluent} ({style})')
    opts = subset.Options()
    opts.glyph_names = True
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    opts.layout_features = []
    sub = subset.Subsetter(opts)
    sub.populate(glyphs=sorted(set(chosen.values())))
    sub.subset(font)
    table = cmap_format_4(4)
    table.platformID, table.platEncID, table.language = 3, 1, 0
    table.cmap = chosen
    font['cmap'].tables = [table]
    for rec in font['name'].names:
        if rec.nameID in (1, 4, 16):
            rec.string = family
        elif rec.nameID == 6:
            rec.string = family.replace(' ', '')
        elif rec.nameID in (2, 17):
            rec.string = 'Regular'
    out = f'{out_dir}/NoteHawkIcons-{style}.ttf'
    font.save(out)
    print(out, len(chosen), 'icons')


def write_constants(path):
    lines = [
        '// Generated by tools/make_icon_font.py. Do not edit by hand; add icons there and re-run it.',
        'namespace NoteHawk.Models;',
        '',
        '/// <summary>Icon glyphs in the NoteHawk icon fonts (Fluent UI System Icons). XAML: {x:Static m:Ic.Home}.</summary>',
        'public static class Ic',
        '{',
    ]
    for name, fluent in ICONS:
        lines.append(f'    public const string {name} = "\\u{CP[name]:04X}"; // {fluent}')
    lines.append('}')
    open(path, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print(path)


if __name__ == '__main__':
    src = sys.argv[1]
    out = 'src/NoteHawk.Desktop/Assets/Fonts'
    build(src, 'Regular', 'NoteHawk Icons', out)
    build(src, 'Filled', 'NoteHawk Icons Filled', out)
    write_constants('src/NoteHawk.Desktop/Models/Ic.cs')
